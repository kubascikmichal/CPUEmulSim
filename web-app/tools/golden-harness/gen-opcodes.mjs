// Generates opcode boundary programs into the golden corpus (gen_*.asm).
// Each case presets CY (via ADI), loads operands with MVI/MXI (flag-neutral) and runs the opcode.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '../../packages/engine/test/corpus');
mkdirSync(out, { recursive: true });

const V8 = [0, 1, 127, 128, 254, 255];
const V16 = [0, 1, 0x7fff, 0x8000, 0xfffe, 0xffff];
const hex = (n) => '0x' + n.toString(16).toUpperCase();
const presetCy = (cy) => (cy ? ['MVI C, 255', 'ADI C, 1'] : ['MVI C, 0', 'ADI C, 0']);

function file(name, lines) {
  writeFileSync(join(out, `gen_${name}.asm`), `; generated by tools/golden-harness/gen-opcodes.mjs\n${lines.join('\n')}\n`);
}

for (const op of ['ADD', 'ADC', 'SUB', 'SUC', 'AND', 'ORR', 'XOR', 'CMP', 'MOV']) {
  const lines = [];
  for (const cy of [0, 1]) for (const a of V8) for (const b of V8) {
    lines.push(...presetCy(cy), `MVI A, ${a}`, `MVI B, ${hex(b)}`, `${op} A, B`);
  }
  for (const a of V8) lines.push(`MVI D, ${a}`, `${op} D, D`);
  file(op.toLowerCase(), lines);
}

for (const op of ['ADI', 'SBI', 'ANI', 'ORI', 'XRI', 'CMI', 'MVI']) {
  const lines = [];
  for (const cy of [0, 1]) for (const a of V8) for (const k of V8) {
    lines.push(...presetCy(cy), `MVI B, ${a}`, `${op} B, ${k}`);
  }
  file(op.toLowerCase(), lines);
}

for (const op of ['INC', 'DEC']) {
  const lines = [];
  for (const cy of [0, 1]) for (const a of V8) lines.push(...presetCy(cy), `MVI A, ${a}`, `${op} A`);
  file(op.toLowerCase(), lines);
}

for (const op of ['INX', 'DCX']) {
  const lines = [];
  for (const cy of [0, 1]) for (const reg of ['S', 'M']) for (const v of V16) {
    lines.push(...presetCy(cy), `MXI ${reg}, ${v}`, `${op} ${reg}`);
  }
  file(op.toLowerCase(), lines);
}

for (const op of ['SHL', 'SHR', 'SCR', 'RTL', 'RCL', 'RTR', 'RCR']) {
  const lines = [];
  for (const cy of [0, 1]) for (const a of [...V8, 0xa5, 0x5a]) for (let k = 1; k <= 8; k++) {
    lines.push(...presetCy(cy), `MVI A, ${a}`, `${op} A, ${k}`);
  }
  file(op.toLowerCase(), lines);
}

console.log('generated opcode corpus in', out);
